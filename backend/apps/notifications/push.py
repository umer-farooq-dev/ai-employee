"""Push alerts to people's devices (MOB-03, API-05, NOTI-03).

Two providers, both set up in Super Admin → Voice & Channels (no keys in code or .env):
- "Web Push" (vendor web_push): browsers and the installed web app. The VAPID key pair is generated by the platform
  when the provider is saved without one. Messages are encrypted for each browser (RFC 8291, aes128gcm) and signed
  with the VAPID key (RFC 8292).
- "Firebase Cloud Messaging" (vendor fcm): the Android / iPhone app; the secret is the Firebase service account JSON.
"""

import base64
import hashlib
import json
import os
import struct
import time
from urllib.parse import urlparse

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.kdf.hkdf import HKDF
from django.utils import timezone

from apps.platform_config.services import get as setting
from apps.providers.adapters import ProviderError, _request, request_raw
from apps.providers.models import Provider

from .models import Device

GONE = ("HTTP 404", "HTTP 410")  # the browser / app unsubscribed: the device is removed


def _b64u(raw):
    return base64.urlsafe_b64encode(raw).rstrip(b"=").decode()


def _b64d(text):
    return base64.urlsafe_b64decode(str(text) + "=" * (-len(str(text)) % 4))


def provider(vendor):
    return Provider.objects.filter(vendor=vendor, is_active=True).exclude(api_key="").first()


# ------------------------------------------------------------------ Web Push (VAPID)
def vapid_keys():
    """→ (private key PEM, public key base64url) for a new provider."""
    key = ec.generate_private_key(ec.SECP256R1())
    pem = key.private_bytes(
        serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption()
    ).decode()
    public = key.public_key().public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint)
    return pem, _b64u(public)


def public_key():
    """The browser needs it to subscribe; empty when Web Push is not set up."""
    p = provider("web_push")
    return (p.config or {}).get("public_key", "") if p else ""


def encrypt(payload, p256dh, auth):
    """RFC 8291 message encryption for one browser subscription."""
    ua_public, auth_secret = _b64d(p256dh), _b64d(auth)
    local = ec.generate_private_key(ec.SECP256R1())
    local_public = local.public_key().public_bytes(
        serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint
    )
    shared = local.exchange(ec.ECDH(), ec.EllipticCurvePublicKey.from_encoded_point(ec.SECP256R1(), ua_public))
    ikm = HKDF(hashes.SHA256(), 32, auth_secret, b"WebPush: info\x00" + ua_public + local_public).derive(shared)
    salt = os.urandom(16)
    cek = HKDF(hashes.SHA256(), 16, salt, b"Content-Encoding: aes128gcm\x00").derive(ikm)
    nonce = HKDF(hashes.SHA256(), 12, salt, b"Content-Encoding: nonce\x00").derive(ikm)
    body = AESGCM(cek).encrypt(nonce, payload + b"\x02", None)  # 0x02: last (only) record
    return salt + struct.pack("!I", 4096) + bytes([len(local_public)]) + local_public + body


def _vapid_header(p, endpoint):
    import jwt

    url = urlparse(endpoint)
    subject = (p.config or {}).get("subject") or f"mailto:{setting('contact.support_email')}"
    token = jwt.encode(
        {"aud": f"{url.scheme}://{url.netloc}", "exp": int(time.time()) + 12 * 3600, "sub": subject},
        p.api_key,
        algorithm="ES256",
    )
    return f"vapid t={token}, k={(p.config or {}).get('public_key', '')}"


def _web(p, device, message):
    body = encrypt(json.dumps(message).encode(), device.keys.get("p256dh", ""), device.keys.get("auth", ""))
    headers = {
        "Authorization": _vapid_header(p, device.token),
        "Content-Encoding": "aes128gcm",
        "Content-Type": "application/octet-stream",
        "TTL": str(setting("notifications.push_ttl_seconds")),
        "Urgency": "high",
    }
    request_raw("POST", device.token, headers, body, timeout=15, as_json=False)


# ------------------------------------------------------------------ Firebase Cloud Messaging (mobile app)
def _fcm(p, device, message):
    from apps.providers.vendors import _google_token

    project = (p.config or {}).get("project_id") or json.loads(p.api_key).get("project_id", "")
    body = {
        "message": {
            "token": device.token,
            "notification": {"title": message["title"], "body": message["body"]},
            "data": {k: str(v) for k, v in message.items()},
            "android": {"priority": "high"},
        }
    }
    _request(
        "POST",
        f"{p.base_url.rstrip('/')}/v1/projects/{project}/messages:send",
        {"Authorization": f"Bearer {_google_token(p, 15)}"},
        body,
        timeout=15,
    )


def send(user, message):
    """message {title, body, url, kind, id} to every device of the person → number of devices reached.
    Raises ProviderError when no push provider is set up or no device took it."""
    devices = list(Device.objects.filter(user=user))
    if not devices:
        raise ProviderError("No device has push switched on.")
    senders = {"web": ("web_push", _web), "android": ("fcm", _fcm), "ios": ("fcm", _fcm)}
    reached, errors = 0, []
    for device in devices:
        vendor, fn = senders[device.platform]
        p = provider(vendor)
        if not p:
            errors.append(f"{vendor} not set up")
            continue
        try:
            fn(p, device, message)
            device.last_used_at, device.failures = timezone.now(), 0
            device.save(update_fields=["last_used_at", "failures", "updated_at"])
            reached += 1
        except ProviderError as exc:
            if str(exc).startswith(GONE) or "UNREGISTERED" in str(exc):
                device.delete()
            else:
                device.failures += 1
                device.save(update_fields=["failures", "updated_at"])
            errors.append(str(exc)[:120])
    if not reached:
        raise ProviderError("; ".join(dict.fromkeys(errors)))
    return reached


# ------------------------------------------------------------------ devices (API-05)
def register(user, platform, token, keys=None, name=""):
    if platform not in dict(Device.PLATFORMS):
        raise ProviderError("Unknown platform.")
    token = str(token or "").strip()
    if not token or len(token) > 4000:
        raise ProviderError("A device token is required.")
    keys = keys or {}
    if platform == "web":
        if not token.startswith("https://") or not keys.get("p256dh") or not keys.get("auth"):
            raise ProviderError("A browser subscription needs its https endpoint and its p256dh / auth keys.")
        keys = {"p256dh": str(keys["p256dh"])[:200], "auth": str(keys["auth"])[:100]}
    key = hashlib.sha256(token.encode()).hexdigest()
    device, _ = Device.objects.update_or_create(
        key=key, defaults={"user": user, "platform": platform, "token": token, "keys": keys, "name": str(name)[:200]}
    )
    return device


def unregister(user, token="", device_id=None):  # nosec B107 — a device token, not a password
    qs = Device.objects.filter(user=user)
    if device_id:
        return qs.filter(pk=device_id).delete()[0]
    return qs.filter(key=hashlib.sha256(str(token).strip().encode()).hexdigest()).delete()[0]
